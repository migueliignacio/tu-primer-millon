create function public.create_farm(p_name text, p_solo boolean, p_materials jsonb)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
  new_farm_id bigint;
  material jsonb;
begin
  if auth.uid() is distinct from '103eadc2-582a-4672-8894-06deaf63f2c7'::uuid then
    raise exception 'No tienes permisos para editar farmeos';
  end if;
  if p_name is null or char_length(btrim(p_name)) not between 1 and 120 then
    raise exception 'Nombre de farmeo inválido';
  end if;
  if p_materials is null or jsonb_typeof(p_materials) <> 'array' or jsonb_array_length(p_materials) = 0 then
    raise exception 'Agrega al menos un material';
  end if;
  insert into public.farms(name, solo, category) values (btrim(p_name), coalesce(p_solo, false), 'materiales') returning id into new_farm_id;
  for material in select value from jsonb_array_elements(p_materials) loop
    insert into public.farm_materials(farm_id, item_id, item_name, item_icon, qty_min, qty_max)
    values (
      new_farm_id,
      (material->>'item_id')::bigint,
      btrim(material->>'item_name'),
      nullif(material->>'item_icon', ''),
      (material->>'qty_min')::integer,
      (material->>'qty_max')::integer
    );
  end loop;
  return new_farm_id;
end;
$$;

create function public.update_farm(p_farm_id bigint, p_name text, p_solo boolean, p_materials jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  material jsonb;
begin
  if auth.uid() is distinct from '103eadc2-582a-4672-8894-06deaf63f2c7'::uuid then
    raise exception 'No tienes permisos para editar farmeos';
  end if;
  if p_name is null or char_length(btrim(p_name)) not between 1 and 120 then
    raise exception 'Nombre de farmeo inválido';
  end if;
  if p_materials is null or jsonb_typeof(p_materials) <> 'array' or jsonb_array_length(p_materials) = 0 then
    raise exception 'Agrega al menos un material';
  end if;
  update public.farms set name = btrim(p_name), solo = coalesce(p_solo, false) where id = p_farm_id;
  if not found then raise exception 'No se encontró el farmeo'; end if;
  delete from public.farm_materials where farm_id = p_farm_id;
  for material in select value from jsonb_array_elements(p_materials) loop
    insert into public.farm_materials(farm_id, item_id, item_name, item_icon, qty_min, qty_max)
    values (
      p_farm_id,
      (material->>'item_id')::bigint,
      btrim(material->>'item_name'),
      nullif(material->>'item_icon', ''),
      (material->>'qty_min')::integer,
      (material->>'qty_max')::integer
    );
  end loop;
end;
$$;


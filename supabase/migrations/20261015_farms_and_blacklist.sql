-- Se vinculan por ID los farmeos existentes y se crean solo los que falten.
do $$
declare
  old_material record;
  new_farm_id bigint;
begin
  for old_material in select * from public.materials order by id loop
    select id into new_farm_id from public.farms where id = old_material.id;
    if new_farm_id is null then
      insert into public.farms(name, solo, category, description)
        values (old_material.item_name, coalesce(old_material.solo, false), 'materiales', old_material.description)
        returning id into new_farm_id;
    end if;
    insert into public.farm_materials(farm_id, item_id, item_name, item_icon, qty_min, qty_max)
      values (new_farm_id, old_material.item_id, old_material.item_name, old_material.item_icon,
              old_material.qty_min, old_material.qty_max);
  end loop;
end;
$$;


alter table public.farms add column name text;
update public.farms as farm
set name = coalesce(
  (select material.item_name from public.materials as material where material.id = farm.id),
  'Farmeo ' || farm.id::text
);
alter table public.farms alter column name set not null;
alter table public.farms add constraint farms_name_check check (char_length(btrim(name)) between 1 and 120);
alter table public.farms alter column category set default 'materiales';

create table public.farm_materials (
  id bigint generated by default as identity primary key,
  farm_id bigint not null references public.farms(id) on delete cascade,
  item_id bigint not null check (item_id > 0),
  item_name text not null check (char_length(btrim(item_name)) > 0),
  item_icon text,
  qty_min integer not null check (qty_min >= 0),
  qty_max integer not null check (qty_max >= qty_min),
  unique (farm_id, item_id)
);
create index farm_materials_farm_id_idx on public.farm_materials(farm_id);

create table public.blacklist_characters (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 80),
  realm text not null check (char_length(btrim(realm)) between 1 and 80),
  created_at timestamptz not null default now()
);
create unique index blacklist_character_identity_idx
  on public.blacklist_characters (lower(btrim(name)), lower(btrim(realm)));

alter table public.farms enable row level security;
alter table public.farm_materials enable row level security;
alter table public.blacklist_characters enable row level security;

